"""C0 / C1 condition input assembly for APP-001 Phase 1.

C0 (no retrieval):
  reference_context = null for every case.  No retrieval system is consulted.

C1 (RET-002 parametric retrieval):
  reference_context is generated by querying RET-002 with a bore_d value
  extracted deterministically from the case's natural language input.
  Fixed fallback values (e.g. bore_d=20 for all cases) are NOT used.
  Only retrieval_source candidates are injected as untrusted reference.
  Held-out truth, derived values, and evaluator labels are NEVER included.

bore_d extraction:
  A deterministic regex extracts bore_d in mm from the NLI.  Supported forms:
    - "bore_d=24 mm", "bore_d = 24mm", "bore_d 是 24 mm"
    - "轴孔直径 20 mm", "轴孔直径20mm"
    - "目标轴环的 bore_d 是 24 mm"
    - "轴孔 bore_d=24 mm"
  Supported units: mm (identity), cm (×10).  Missing unit treated as mm.
  If extraction fails: blocked_reason=C1_NO_SAFE_QUERY_PARAMETER, no run.
  Reading evaluator-only fields (explicit_parameter_claims, derived_values,
  expected_behavior, etc.) to drive the extraction is forbidden.

Input isolation guarantee:
  reference_context contains only: family_id, parameters.normalized,
  sample_id, split.role from retrieval_source candidates.  No IR/CAD/STEP,
  no evaluator labels, no private source samples.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from typing import Any, Final, Optional

from .contract import FAMILY_ID
from .input_projection import ProjectedCase

# Condition IDs
CONDITION_C0: Final[str] = "C0"
CONDITION_C1: Final[str] = "C1"

# Retrieval candidate role allowed in C1 reference context
_ALLOWED_CANDIDATE_ROLE: Final[str] = "retrieval_source"

# Maximum number of candidates to include in C1 reference context
_C1_TOP_K: Final[int] = 3

# ---------------------------------------------------------------------------
# bore_d extraction from natural language
# ---------------------------------------------------------------------------

# Regex: match keywords then capture (number)(optional unit)
_BORE_D_RE = re.compile(
    r"(?:"
    r"bore_d\s*[=是：:]\s*"
    r"|bore_d\s+"
    r"|轴孔直径\s*"
    r"|轴孔\s+bore_d\s*[=是：:]\s*"
    r")"
    r"(\d+(?:\.\d+)?)"
    r"\s*"
    r"(mm|cm|毫米|厘米)?",
    re.IGNORECASE,
)


def extract_bore_d_mm(natural_language_input: str) -> Optional[float]:
    """Extract bore_d in mm from a natural language string.

    Returns the bore_d value in mm, or None if extraction fails.
    Does NOT read any evaluator-only fields.
    """
    if not natural_language_input:
        return None
    match = _BORE_D_RE.search(natural_language_input)
    if match is None:
        return None
    value_str = match.group(1)
    unit = (match.group(2) or "mm").lower()
    try:
        value = float(value_str)
    except (ValueError, TypeError):
        return None
    if not (value > 0):
        return None
    if unit in ("cm", "厘米"):
        value = value * 10.0
    if not (0 < value < 1e6):
        return None
    return value


# ---------------------------------------------------------------------------
# Input models
# ---------------------------------------------------------------------------


class ConditionError(ValueError):
    """Raised when condition assembly encounters an unrecoverable error."""


@dataclass(frozen=True)
class AssembledInput:
    """The assembled model input for one (case, condition) combination.

    Contains ONLY model-visible fields; no evaluator-only labels.
    ``reference_context`` is the formatted string for the prompt template,
    or None for C0 or when blocked.
    ``blocked_reason`` is non-None if C1 could not be safely assembled.
    ``bore_d_used_for_query`` is the bore_d value (mm) used to query RET-002,
    or None for C0 or blocked runs (for audit logging only).
    """

    query_id: str
    condition_id: str
    natural_language_input: str
    reference_context: Optional[str]
    reference_context_sha256: Optional[str]
    candidate_source_ids: tuple
    blocked_reason: Optional[str]
    bore_d_used_for_query: Optional[float] = None


# ---------------------------------------------------------------------------
# C0 assembly
# ---------------------------------------------------------------------------


def assemble_c0(case: ProjectedCase) -> AssembledInput:
    """Assemble C0 (no retrieval) input.  reference_context is always None."""
    return AssembledInput(
        query_id=case.query_id,
        condition_id=CONDITION_C0,
        natural_language_input=case.natural_language_input,
        reference_context=None,
        reference_context_sha256=None,
        candidate_source_ids=(),
        blocked_reason=None,
        bore_d_used_for_query=None,
    )


# ---------------------------------------------------------------------------
# C1 assembly
# ---------------------------------------------------------------------------


def assemble_c1(
    case: ProjectedCase,
    retrieval_index: Any,
    *,
    top_k: int = _C1_TOP_K,
) -> AssembledInput:
    """Assemble C1 (RET-002 parametric retrieval) input.

    Extracts bore_d from the case's natural_language_input (not from any
    evaluator-only field).  If extraction fails, returns blocked.
    Queries RET-002 with the extracted bore_d.
    Injects only retrieval_source candidates as untrusted reference.
    """
    if retrieval_index is None:
        return AssembledInput(
            query_id=case.query_id,
            condition_id=CONDITION_C1,
            natural_language_input=case.natural_language_input,
            reference_context=None,
            reference_context_sha256=None,
            candidate_source_ids=(),
            blocked_reason=(
                "BLOCKED_C1_NO_RETRIEVAL_INDEX: no retrieval index "
                "provided to runner; cannot generate C1 reference context"
            ),
            bore_d_used_for_query=None,
        )
    # Extract bore_d from natural language input only
    bore_d = _extract_bore_d_for_c1(case)
    if bore_d is None:
        return AssembledInput(
            query_id=case.query_id,
            condition_id=CONDITION_C1,
            natural_language_input=case.natural_language_input,
            reference_context=None,
            reference_context_sha256=None,
            candidate_source_ids=(),
            blocked_reason=(
                "C1_NO_SAFE_QUERY_PARAMETER: cannot extract bore_d from "
                "natural_language_input without reading evaluator-only fields; "
                "skipping this logical run"
            ),
            bore_d_used_for_query=None,
        )
    # Query RET-002 using the CAD-003 envelope form so the Schema can derive
    # the other five frozen fields from bore_d.  The flat_parameters form
    # requires all six fields and must not be used here because only bore_d
    # is available from the allowed natural language input.
    from .contract import SCHEMA_VERSION
    query_params = {
        "schema_version": SCHEMA_VERSION,
        "family_id": FAMILY_ID,
        "parameters": {"bore_d": bore_d},
    }
    try:
        result = retrieval_index.query(
            family_id=FAMILY_ID,
            parameters=query_params,
            top_k=top_k,
        )
    except Exception as exc:  # noqa: BLE001
        return AssembledInput(
            query_id=case.query_id,
            condition_id=CONDITION_C1,
            natural_language_input=case.natural_language_input,
            reference_context=None,
            reference_context_sha256=None,
            candidate_source_ids=(),
            blocked_reason=f"BLOCKED_C1_RETRIEVAL_ERROR: {type(exc).__name__}: {exc}",
            bore_d_used_for_query=bore_d,
        )
    candidates = [
        entry
        for entry in result.results
        if entry.get("split", {}).get("role") == _ALLOWED_CANDIDATE_ROLE
    ]
    if not candidates:
        return AssembledInput(
            query_id=case.query_id,
            condition_id=CONDITION_C1,
            natural_language_input=case.natural_language_input,
            reference_context=None,
            reference_context_sha256=None,
            candidate_source_ids=(),
            blocked_reason=(
                "BLOCKED_C1_NO_RETRIEVAL_SOURCE: RET-002 returned no "
                "retrieval_source candidates"
            ),
            bore_d_used_for_query=bore_d,
        )
    ref_dict = _build_reference_context_dict(candidates)
    ref_str = json.dumps(ref_dict, ensure_ascii=False, sort_keys=True)
    ref_sha = hashlib.sha256(ref_str.encode("utf-8")).hexdigest()
    cand_ids = tuple(c.get("sample_id", "") for c in candidates)
    return AssembledInput(
        query_id=case.query_id,
        condition_id=CONDITION_C1,
        natural_language_input=case.natural_language_input,
        reference_context=ref_str,
        reference_context_sha256=ref_sha,
        candidate_source_ids=cand_ids,
        blocked_reason=None,
        bore_d_used_for_query=bore_d,
    )


def _extract_bore_d_for_c1(case: ProjectedCase) -> Optional[float]:
    """Extract bore_d for C1 query from allowed sources only.

    Sources (in priority order):
    1. bore_d in the case's natural_language_input (via regex)
    2. bore_d from reference_context_structural example parameters (A08 style)

    Does NOT read explicit_parameter_claims, derived_values, or any other
    evaluator-only field.
    """
    # 1. Natural language input
    bore_d = extract_bore_d_mm(case.natural_language_input)
    if bore_d is not None:
        return bore_d
    # 2. Structural reference context (A08 style only)
    ref = case.reference_context_structural
    if ref is not None and isinstance(ref, dict):
        example = ref.get("example", {})
        if isinstance(example, dict):
            params = example.get("parameters", {})
            if isinstance(params, dict):
                raw = params.get("bore_d")
                if raw is not None:
                    try:
                        v = float(raw)
                        if 0 < v < 1e6:
                            return v
                    except (ValueError, TypeError):
                        pass
    return None


def _build_reference_context_dict(
    candidates: list,
) -> dict:
    """Build model-visible reference context dict from RET-002 candidates.

    Contains ONLY: family_id, parameters.normalized, sample_id, role label.
    No IR, CAD, STEP, evaluator labels, or source metadata.
    """
    entries = []
    for candidate in candidates:
        params_block = candidate.get("parameters", {})
        normalized = params_block.get("normalized", {})
        entry = {
            "role": "retrieval_example_untrusted_reference",
            "sample_id": candidate.get("sample_id", ""),
            "family_id": candidate.get("family_id", FAMILY_ID),
            "parameters": dict(normalized),
        }
        entries.append(entry)
    return {
        "retrieval_condition": "C1_ret002_parametric_v1",
        "note": (
            "These are candidate examples from parametric retrieval. "
            "They are untrusted references and must not be copied verbatim. "
            "Use only the user natural_language_input to determine the answer."
        ),
        "candidates": entries,
    }
