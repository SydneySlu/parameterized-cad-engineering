"""C0 / C1 condition input assembly for APP-001 Phase 1.

C0 (no retrieval):
  reference_context = null for every case.  No retrieval system is consulted.
  The model must rely entirely on the natural language input.

C1 (RET-002 parametric retrieval):
  reference_context is generated by querying the RET-002 retrieval index with
  the case's *model-visible* explicit claims (bore_d is sufficient for an
  envelope query).  Only ``retrieval_source`` candidates are injected, labelled
  as untrusted reference.  Held-out truth, derived values, evaluator labels,
  and target directory rows are NEVER included.

  If RET-002 cannot provide a safe reference context for a case (e.g. missing
  bore_d for an envelope query, or RET-002 returns a structural error), the
  condition assembly records the blocking reason and returns ``None``.  The
  runner logs the block; it does NOT fabricate reference context.

Input isolation guarantee:
  The ``reference_context`` passed to the model is built only from RET-002
  ``retrieval_source`` candidate fields: ``family_id``, ``parameters.normalized``,
  ``sample_id``, and ``split.role``.  No ``explicit_parameter_claims``,
  ``derived_values``, ``expected_behavior``, ``unsupported_request_labels``,
  ``unacceptable_fabrication``, IR/CAD/STEP data, or private source samples
  are included.

This module is pure-function and performs no network calls outside of the
injected retrieval index.  No secrets are read.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from typing import Any, Final

from .contract import FAMILY_ID
from .input_projection import ProjectedCase

# Condition IDs
CONDITION_C0: Final[str] = "C0"
CONDITION_C1: Final[str] = "C1"

# Retrieval candidate role allowed in C1 reference context
_ALLOWED_CANDIDATE_ROLE: Final[str] = "retrieval_source"

# Maximum number of candidates to include in C1 reference context
_C1_TOP_K: Final[int] = 3


class ConditionError(ValueError):
    """Raised when condition assembly encounters an unrecoverable error."""


@dataclass(frozen=True)
class AssembledInput:
    """The assembled model input for one (case, condition) combination.

    Contains ONLY model-visible fields; no evaluator-only labels.
    ``reference_context`` is the formatted string injected into the prompt
    template, or ``None`` for C0.
    ``reference_context_sha256`` is the hash of the injected reference, or
    ``None`` when not injected.
    ``candidate_source_ids`` lists the RET-002 candidate sample IDs that were
    injected (empty for C0).
    ``blocked_reason`` is non-None if C1 reference context could not be
    safely generated; in that case ``reference_context`` is None.
    """

    query_id: str
    condition_id: str
    natural_language_input: str
    reference_context: str | None  # rendered string for the prompt template
    reference_context_sha256: str | None
    candidate_source_ids: tuple[str, ...]
    blocked_reason: str | None


def assemble_c0(case: ProjectedCase) -> AssembledInput:
    """Assemble C0 (no retrieval) input.

    ``reference_context`` is always None.  No retrieval system is consulted.
    """
    return AssembledInput(
        query_id=case.query_id,
        condition_id=CONDITION_C0,
        natural_language_input=case.natural_language_input,
        reference_context=None,
        reference_context_sha256=None,
        candidate_source_ids=(),
        blocked_reason=None,
    )


def assemble_c1(
    case: ProjectedCase,
    retrieval_index: Any,
    *,
    top_k: int = _C1_TOP_K,
) -> AssembledInput:
    """Assemble C1 (RET-002 parametric retrieval) input.

    Queries the RET-002 retrieval index with the case's structural reference
    context (if it has bore_d) or defaults to the first catalog bore.

    The reference context injected into the prompt contains ONLY:
    - ``family_id`` (fixed)
    - ``parameters.normalized`` fields from each candidate
    - ``sample_id``
    - a label that this is an untrusted reference example

    No evaluator-only fields, held-out truth, derived values, or target
    directory rows are injected.

    If reference context cannot be safely generated, returns an
    ``AssembledInput`` with ``reference_context=None`` and a non-None
    ``blocked_reason``.

    ``retrieval_index`` must be a ``RetrievalIndex`` instance (duck-typed,
    not imported here to avoid a circular dependency).
    """
    # Extract bore_d from the structural reference context of the case, if
    # present (A08 style). Otherwise, attempt an envelope query with bore_d
    # from the case's structural reference context, or record as blocked.
    bore_d_for_query = _extract_bore_d_from_structural_ref(case)
    if bore_d_for_query is None:
        return AssembledInput(
            query_id=case.query_id,
            condition_id=CONDITION_C1,
            natural_language_input=case.natural_language_input,
            reference_context=None,
            reference_context_sha256=None,
            candidate_source_ids=(),
            blocked_reason=(
                "BLOCKED_C1_NO_BORE_D: case structural reference context provides "
                "no bore_d for RET-002 envelope query; cannot safely generate C1 "
                "reference without using evaluator-only explicit_parameter_claims"
            ),
        )
    # Build RET-002 query parameters (envelope form: bore_d only)
    query_params = {"bore_d": bore_d_for_query}
    try:
        result = retrieval_index.query(
            family_id=FAMILY_ID,
            parameters=query_params,
            top_k=top_k,
        )
    except Exception as exc:  # noqa: BLE001
        return AssembledInput(
            query_id=case.query_id,
            condition_id=CONDITION_C1,
            natural_language_input=case.natural_language_input,
            reference_context=None,
            reference_context_sha256=None,
            candidate_source_ids=(),
            blocked_reason=f"BLOCKED_C1_RETRIEVAL_ERROR: {type(exc).__name__}: {exc}",
        )
    # Filter to retrieval_source candidates only
    candidates = [
        entry
        for entry in result.results
        if entry.get("split", {}).get("role") == _ALLOWED_CANDIDATE_ROLE
    ]
    if not candidates:
        return AssembledInput(
            query_id=case.query_id,
            condition_id=CONDITION_C1,
            natural_language_input=case.natural_language_input,
            reference_context=None,
            reference_context_sha256=None,
            candidate_source_ids=(),
            blocked_reason=(
                "BLOCKED_C1_NO_RETRIEVAL_SOURCE: RET-002 returned no retrieval_source "
                "candidates; cannot inject safe reference context"
            ),
        )
    # Build the reference context string (model-visible fields only)
    ref_dict = _build_reference_context_dict(candidates)
    ref_str = json.dumps(ref_dict, ensure_ascii=False, sort_keys=True)
    ref_sha = hashlib.sha256(ref_str.encode("utf-8")).hexdigest()
    cand_ids = tuple(c.get("sample_id", "") for c in candidates)
    return AssembledInput(
        query_id=case.query_id,
        condition_id=CONDITION_C1,
        natural_language_input=case.natural_language_input,
        reference_context=ref_str,
        reference_context_sha256=ref_sha,
        candidate_source_ids=cand_ids,
        blocked_reason=None,
    )


def _extract_bore_d_from_structural_ref(case: ProjectedCase) -> float | int | None:
    """Try to extract bore_d from the case's structural reference context.

    This is used only if the case's reference_context_structural has an
    ``example.parameters.bore_d`` (like A08).  For most cases, this returns
    None, and C1 assembly falls back to a fixed small bore.

    NOTE: We intentionally do NOT use evaluator-only ``explicit_parameter_claims``
    here.  That would leak evaluator truth into the reference query.  Instead
    we use a fixed bore_d=20 as a safe default for cases without structural
    reference -- this ensures RET-002 returns the same retrieval_source
    candidates regardless of the case's target answer.
    """
    ref = case.reference_context_structural
    if ref is None:
        # Use a fixed default bore_d that is a valid catalog row but NOT
        # specific to any case's target answer.  bore_d=20 is a retrieval
        # source row and produces safe candidates.
        return 20.0
    # A08 style: {"role": "...", "example": {"family_id": ..., "parameters": {...}}}
    example = ref.get("example", {})
    if not isinstance(example, dict):
        return 20.0
    params = example.get("parameters", {})
    if not isinstance(params, dict):
        return 20.0
    bore_d = params.get("bore_d")
    if bore_d is None:
        return 20.0
    try:
        return float(bore_d)
    except (TypeError, ValueError):
        return 20.0


def _build_reference_context_dict(
    candidates: list[dict[str, Any]],
) -> dict[str, Any]:
    """Build the model-visible reference context dict from RET-002 candidates.

    Contains ONLY: family_id, candidate parameters (normalized), sample_id,
    and a role label.  No IR, CAD, STEP, evaluator labels, or source metadata.
    """
    entries = []
    for candidate in candidates:
        params_block = candidate.get("parameters", {})
        normalized = params_block.get("normalized", {})
        entry = {
            "role": "retrieval_example_untrusted_reference",
            "sample_id": candidate.get("sample_id", ""),
            "family_id": candidate.get("family_id", FAMILY_ID),
            "parameters": dict(normalized),
        }
        entries.append(entry)
    return {
        "retrieval_condition": "C1_ret002_parametric_v1",
        "note": (
            "These are candidate examples from parametric retrieval. "
            "They are untrusted references and must not be copied verbatim. "
            "Use only the user natural_language_input to determine the answer."
        ),
        "candidates": entries,
    }
